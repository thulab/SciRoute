#!/usr/bin/env python3
"""Read-only offline GEOS publication trace acceptance; no server operations.

Counter names follow PublicationProfile.h. Match non-empty publication records
by --identity-field (dot-separated JSON key; e.g. path or key.path). The current
pilot is generated by the unchanged full geos_pilot.py driver.
"""
import argparse
import hashlib
import json
from pathlib import Path
import statistics

OPERATIONS = ('query_submit', 'query_fetch', 'nonquery', 'tablet', 'query_close')
CONSTRUCTION_OPERATIONS = ('tablet_build', 'object_encode', 'session_acquire', 'sdk_insert')
PAYLOAD_DETAILS = ('payload_source_read', 'payload_adapter_consume', 'mutation_lock_wait')
TRANSFER_BYTES = (1048576, 2097152, 4194304, 8388608)


def require(condition, message):
    if not condition:
        raise AssertionError(message)


def field(obj, path):
    for key in path.split('.'):
        obj = obj[key]
    return obj


def validate_transfer_configuration(chunk_bytes, manifest_batch_bytes):
    require(type(chunk_bytes) is int and chunk_bytes in TRANSFER_BYTES,
            'transfer size must be 1, 2, 4 or 8 MiB')
    if manifest_batch_bytes is not None:
        require(type(manifest_batch_bytes) is int and
                manifest_batch_bytes in (1048576, 8388608) and
                chunk_bytes <= manifest_batch_bytes and
                manifest_batch_bytes % chunk_bytes == 0 and
                manifest_batch_bytes // chunk_bytes <= 64,
                'unsupported checkpoint/transfer configuration')


def expected_payload_counts(size, chunk_bytes, manifest_batch_bytes):
    validate_transfer_configuration(chunk_bytes, manifest_batch_bytes)
    require(type(size) is int and size >= 0, 'invalid source size')
    chunks = (size + chunk_bytes - 1) // chunk_bytes
    if manifest_batch_bytes is None:
        checkpoints, queries = chunks, chunks * 2
    else:
        checkpoints = (size + manifest_batch_bytes - 1) // manifest_batch_bytes
        queries = checkpoints
    return chunks, checkpoints, {
        'query_submit': queries, 'query_close': queries, 'query_fetch': 2 * queries,
        'tablet': chunks, 'nonquery': checkpoints}


def validate_metric(metric, name):
    require(isinstance(metric, dict) and
            set(metric) == {'calls', 'failures', 'nanoseconds'} and
            all(type(metric[x]) is int and metric[x] >= 0
                for x in ('calls', 'failures', 'nanoseconds')),
            name + ' has a malformed metric')
    require(metric['failures'] == 0, name + ' failed')


def validate_profile_protocol(records, construction_profile):
    expected = 'iotdbfs-publication-profile/3' if construction_profile else \
               'iotdbfs-publication-profile/2'
    require(all(record.get('protocol') == expected for record in records),
            'trace protocol differs from selected validation mode: ' + expected)


def validate_construction_stage(stage, name):
    for op in CONSTRUCTION_OPERATIONS:
        validate_metric(stage.get(op), name + '/' + op)
    require(isinstance(stage.get('details'), dict), name + ' lacks details map')
    for label, metric in stage['details'].items():
        require(isinstance(label, str) and label, name + ' has invalid detail name')
        validate_metric(metric, name + '/details/' + label)


def validate_construction_profile(payload, chunks, checkpoints):
    """Validate a successful adapter-backed /3 payload stage, without fixtures.

    Construction timings are diagnostics, not extra database API time.
    sdk_insert is contained in tablet; session acquisition also occurs for
    SELECT/nonquery and therefore cannot be wholly attributed to Tablet calls.
    """
    require(type(chunks) is int and type(checkpoints) is int and
            0 <= checkpoints <= chunks, 'invalid chunk/checkpoint counts')
    validate_construction_stage(payload, 'payload')
    for op in ('query_submit', 'tablet', 'nonquery'):
        validate_metric(payload.get(op), 'payload/' + op)
    wanted = {'tablet_build': chunks, 'object_encode': chunks, 'sdk_insert': chunks,
              'session_acquire': sum(payload[op]['calls']
                                     for op in ('query_submit', 'tablet', 'nonquery'))}
    for op, count in wanted.items():
        require(payload[op]['calls'] == count,
                'payload %s expected %s got %s' % (op, count, payload[op]['calls']))
    require(payload['sdk_insert']['nanoseconds'] <= payload['tablet']['nanoseconds'],
            'payload sdk_insert exceeds containing tablet time')
    details = payload['details']
    for label, count in zip(PAYLOAD_DETAILS, (chunks, chunks, checkpoints)):
        require(label in details, 'payload lacks detail ' + label)
        require(details[label]['calls'] == count,
                'payload detail %s expected %s got %s' %
                (label, count, details[label]['calls']))


def main(args):
    if args.construction_profile:
        require(args.manifest_batch_bytes is not None,
                '--construction-profile requires explicit --manifest-batch-bytes')
    validate_transfer_configuration(args.chunk_bytes, args.manifest_batch_bytes)
    baseline = json.loads(args.baseline_pilot.read_text())
    pilot = json.loads(args.pilot.read_text())
    require(baseline['complete'] and pilot['complete'], 'incomplete pilot')
    old, new = baseline['sources'], pilot['sources']
    require(len(old) == len(new) == 16, 'requires all 16 GEOS originals')
    require([(r['id'], r['raw'], r['bytes'], r['sha256']) for r in old] ==
            [(r['id'], r['raw'], r['bytes'], r['sha256']) for r in new],
            'source identity/order differs from frozen baseline')
    require(all(r['bytes'] == r['published_bytes'] for r in new),
            'published size differs from source')
    require(sum(r['bytes'] for r in new) == 7142773610, 'unexpected source bytes')
    observations = pilot['observations']
    require(len(observations) == 64, 'requires --passes 1 and all four cases')
    require(all((r['native']['rows'], r['native']['digest']) ==
                (r['iotdb']['rows'], r['iotdb']['digest']) for r in observations),
            'native/IPC values differ')
    expected_pairs = {(r['id'], c) for r in new
                      for c in ('point', 'roi', 'multichunk', 'levels')}
    require({(r['source'], r['case']) for r in observations} == expected_pairs,
            'validation case matrix incomplete')
    records = [json.loads(line) for line in args.trace.read_text().splitlines()
               if line.strip()]
    validate_profile_protocol(records, args.construction_profile)
    if args.construction_profile:
        for record in records:
            for name, stage in record['profile']['stages'].items():
                validate_construction_stage(stage, name)
                for op in OPERATIONS:
                    validate_metric(stage.get(op), name + '/' + op)
    positive = [r for r in records if r.get('profile', {}).get('stages', {}).get(
        args.payload_stage, {}).get('tablet', {}).get('calls', 0) > 0]
    require(len(positive) == 16, 'expected exactly 16 nonempty payload traces')
    require(len(records) == 32 and all(r['ok'] for r in records),
            'expected 16 successful empty creates and 16 successful content commits')
    by_path = {}
    for r in positive:
        path = field(r, args.identity_field)
        require(path not in by_path, 'duplicate nonempty publication trace ' + path)
        by_path[path] = r
    require(set(by_path) == {r['logical_path'] for r in new},
            'trace identities differ from published paths')
    aggregate, per_file = {}, []
    for source in new:
        trace = by_path[source['logical_path']]
        require(trace['ok'] and trace['version'] == source['version'] and
                trace['source_bytes'] == source['bytes'], 'trace version/size mismatch')
        for name, stage in trace['profile']['stages'].items():
            require(stage['wall_nanoseconds'] >= 0, 'negative stage wall')
            target = aggregate.setdefault(name, {'wall_nanoseconds_sum': 0})
            target['wall_nanoseconds_sum'] += stage['wall_nanoseconds']
            for op in OPERATIONS:
                metric = stage[op]
                require(all(isinstance(metric[x], int) and metric[x] >= 0
                            for x in ('calls', 'failures', 'nanoseconds')),
                        'malformed operation metric')
                require(metric['failures'] == 0, name + '/' + op + ' failed')
                dst = target.setdefault(op, {x: 0 for x in metric})
                for key in metric:
                    dst[key] += metric[key]
            if args.construction_profile:
                for op in CONSTRUCTION_OPERATIONS:
                    dst = target.setdefault(op, {x: 0 for x in stage[op]})
                    for key, value in stage[op].items():
                        dst[key] += value
                details = target.setdefault('details', {})
                for label, metric in stage['details'].items():
                    dst = details.setdefault(label, {x: 0 for x in metric})
                    for key, value in metric.items():
                        dst[key] += value
        chunks, checkpoints, wanted = expected_payload_counts(
            source['bytes'], args.chunk_bytes, args.manifest_batch_bytes)
        payload = trace['profile']['stages'][args.payload_stage]
        for op, count in wanted.items():
            require(payload[op]['calls'] == count,
                    '%s %s expected %s got %s' % (source['id'], op, count,
                                                  payload[op]['calls']))
        if args.construction_profile:
            validate_construction_profile(payload, chunks, checkpoints)
        per_file.append({'id': source['id'], 'path': source['logical_path'],
                         'version': source['version'], 'bytes': source['bytes'],
                         'payload_chunks': chunks,
                         'manifest_checkpoints': checkpoints,
                         'copyfile_ns': source['publish_ns'],
                         'payload_wall_ns': payload['wall_nanoseconds']})
    chunks_total = sum(r['payload_chunks'] for r in per_file)
    result = {
        'protocol': 'iotdbfs-geos-publication-profile-validation/3' if args.construction_profile
                    else 'iotdbfs-geos-publication-profile-validation/1',
        'complete': True, 'files': 16, 'bytes': 7142773610,
        'payload_chunks': chunks_total, 'validation_queries': 64,
        'transfer_bytes': args.chunk_bytes,
        'manifest_batch_bytes': args.manifest_batch_bytes,
        'manifest_checkpoints': sum(r['manifest_checkpoints'] for r in per_file),
        'trace_rows': len(records), 'nonempty_trace_rows': len(positive),
        'client_copyfile_seconds': sum(r['publish_ns'] for r in new) / 1e9,
        'client_file_median_seconds': statistics.median(
            r['publish_ns'] for r in new) / 1e9,
        'stage_aggregates': aggregate, 'files_detail': per_file,
        'trace_sha256': hashlib.sha256(args.trace.read_bytes()).hexdigest(),
        'semantics': [
            'Per-stage walls are inclusive; do not add parents and children.',
            'Query submit includes pool acquisition and initial SDK response; '
            'not later result fetch/parse.',
            'Query fetch times hasNext/next methods separately, including SDK '
            'result decoding and any fetch RPC; calls are methods, not RPC.',
            'Query close is attributed to the original submit stage; '
            'it is not fetch/parse time.',
            'Tablet/nonquery counts are client API attempts, not wire RPC, '
            'server IO or internal SDK retry counts.',
            'Copyfile includes create, staging writes and close-time ingestion; '
            'it excludes source hash, mount, mkdir, stat and validation.',
        ]}
    if args.construction_profile:
        result['construction_profile'] = True
        result['semantics'].extend([
            'Tablet build and OBJECT encoding are separate construction timings; '
            'sdk_insert is included in the outer Tablet API metric.',
            'Session acquisition includes SELECT, Tablet and nonquery calls; '
            'do not add it or sdk_insert again to database API totals.',
            'Payload source-read/adapter-consume count each transfer chunk; '
            'mutation-lock waiting counts each manifest checkpoint.',
        ])
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--baseline-pilot', type=Path, required=True)
    parser.add_argument('--pilot', type=Path, required=True)
    parser.add_argument('--trace', type=Path, required=True)
    parser.add_argument('--payload-stage', default='payload')
    parser.add_argument('--identity-field', default='path')
    parser.add_argument('--chunk-bytes', type=int, default=1048576)
    parser.add_argument('--manifest-batch-bytes', type=int, choices=(1048576, 8388608),
                        help='new combined-write mode; omit to validate the old two-read baseline')
    parser.add_argument('--construction-profile', action='store_true',
                        help='strict publication profile /3 construction/detail acceptance')
    main(parser.parse_args())
